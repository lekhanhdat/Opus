        private void AddRDFRecordIntegrityCheckBlock(ref RecordVEOClassV3.Record recordVers, RecordVEO_M11RDFRecord M11)
        {
            if (M11.M62 != null)
            {
                var mIntegrityCheck = new RecordVEOClassV3.RecordIntegrityCheck();

                if (M11.M62.M63 != null)
                {
                    mIntegrityCheck.HashFunctionName = VEOV3CustomizeProperty.GetPropertyValueByLevel(M11.M62.M63.SharePointMetadataAsSource, M11.M62.M63.DefaultValue, M11.M62.M63.SharePointMetadata, _contentParams);
                }
                if (!string.IsNullOrEmpty(mIntegrityCheck.HashFunctionName) && !string.IsNullOrEmpty(_contentParams.VContentFullPath))
                {
                    try
                    {
                        using (var stream = File.OpenRead(_contentParams.VContentFullPath))
                        {
                            mIntegrityCheck.MessageDigest = VEOV3CommonMethod.ComputeHashAsBase64(stream, mIntegrityCheck.HashFunctionName);
                        }
                        if (string.Equals(mIntegrityCheck.HashFunctionName, VEOV3CommonString.ALGORITHM_SHA512, StringComparison.OrdinalIgnoreCase))
                        {
                            _contentParams.VContentHashValue = mIntegrityCheck.MessageDigest;
                        }
                    }
                    catch (Exception e)
                    {
                        mLog.Error($"An error occurred while hashing the content of file {_contentParams.VName}, HashFunctionName: {mIntegrityCheck.HashFunctionName} so convert base64 instead. EX: {e}");
                        _contentParams.VContentHashValue = string.Empty;
                        return;
                    }
                }

                recordVers.IntegrityCheck = VEOV3CommonMethod.FilteredValidValue(mIntegrityCheck);
