        public static bool IsStorageObject(SFObjectProxy sfObjectProxy)
        {
            var sObjectName = sfObjectProxy.Name;
            return IsFileStorageObject(sObjectName) || IsDataStorageObject(sObjectName) || sfObjectProxy.Custom;
        }
        

        public static bool IsDataStorageObject(string objectName)
        {
            return DataStorageObjects.Contains(objectName, StringComparer.OrdinalIgnoreCase) || FieldServiceObjects.Contains(objectName, StringComparer.OrdinalIgnoreCase);
        }

        public static bool IsFileStorageObject(string objectName)
        {
            return FileStorageObjects.Contains(objectName, StringComparer.OrdinalIgnoreCase);
        }
