        public static RecordVEOClassV3.VEOHistory InitVEOHistory(VEOHistoryXML historyVEOXML)
        {
            _historyVEOXML = historyVEOXML;
            return new RecordVEOClassV3.VEOHistory();
        }

        public void GenerateVEOHistory(ref RecordVEOClassV3.VEOHistory mVEOHistory)
        {
            if (_historyVEOXML != null && _historyVEOXML.M1 != null)
            {
                foreach (var M3 in _historyVEOXML.M1.M3)
                {
                    var mEvent = new RecordVEOClassV3.Event
                    {
                        EventDateTime = M3.M4?.DefaultValue?.Equals("@TimeNow@", StringComparison.OrdinalIgnoreCase) == true ? DateTime.Now.ToString(VEOV3CommonString.FORMAT_DATETIME_V3) : M3.M4?.DefaultValue,
                        EventType = M3.M5?.DefaultValue,
                        Initiator = M3.M6?.DefaultValue,
                        Description = VEOV3CommonMethod.FilteredValidValue(M3.M23?.Where(d => d.DefaultValue.IsNotNullOrEmpty()).Select(d => d.DefaultValue).ToList()),
                        Error = VEOV3CommonMethod.FilteredValidValue(M3.M7?.Where(d => d.DefaultValue.IsNotNullOrEmpty()).Select(d => d.DefaultValue).ToList()),
                    };

                    (mVEOHistory.Event ??= []).Add(VEOV3CommonMethod.FilteredValidValue(mEvent));
                }
            }
        }

        /// <summary>
        /// VEOSignature V3 is generated by VEOHistory or VEOContent file.
        /// </summary>
        /// <returns></returns>
        public void GenerateVEOSignature(ref RecordVEOClassV3.SignatureBlock mSignatureBlock, MemoryStream memoryStream)
        {
            mSignatureBlock.Version = VEOV3CommonString.VEO_VERSION;
            mSignatureBlock.SignatureAlgorithm = VEOV3CommonString.ALGORITHMID_SHA512WITHRSA;
            mSignatureBlock.SignatureDateTime = VEOV3CommonString.FORMAT_DATETIME_V3;
            mSignatureBlock.Signer = VEOCommonString.SIGNER;

            byte[] result = SHA512WithRSASignature.Signature(memoryStream.ToArray());
            mSignatureBlock.Signature = VEOV3CommonMethod.AddValueNewLine(Convert.ToBase64String(result));
            mSignatureBlock.CertificateChain = new string[1];
            mSignatureBlock.CertificateChain[0] = VEOV3CommonMethod.AddValueNewLine(Convert.ToBase64String(AveCertificateOperation.ExportCertificateWithCertFormat()));
        }

        public void AddInformationObjectBlock(ref RecordVEOClassV3.VEOContent vEOContentObj, RecordVEOParametersV3 vParams)
        {
            if (_contentVEOXML == null) return;
            _contentParams = vParams;
            RecordVEO_M1_VEOContent M1 = _contentVEOXML.M1;
            if (M1 == null) return;
            foreach (var M4 in M1.M4)
            {
                var informationObject = new RecordVEOClassV3.InformationObject();
                informationObject.InformationObjectType = vParams.VIOType;
                informationObject.InformationObjectDepth = vParams.VIODepth;

                AddMetadataPackageBlock(ref informationObject, M4);

                if (vParams.HasIP)
                {
                    AddInformationPieceBlock(ref informationObject, M4);
                }

                (vEOContentObj.InformationObject ??= []).Add(informationObject);
            }
        }

