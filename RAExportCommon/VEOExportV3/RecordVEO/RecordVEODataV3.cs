        private void AddContentFileBlock(ref RecordVEOClassV3.InformationPiece mInformationPiece, RecordVEO_M68_InformationPiece M68)
        {
            // always generate value by ourself
            var contentFile = new RecordVEOClassV3.ContentFile
            {
                PathName = _contentParams.VContentPathName,
            };
            try
            {
                if (string.IsNullOrEmpty(_contentParams.VContentFullPath)) throw new Exception($"Cannot get the content of this file");
                using (var stream = File.OpenRead(_contentParams.VContentFullPath))
                {
                    contentFile.HashValue = string.IsNullOrEmpty(_contentParams.VContentHashValue)
                        ? VEOV3CommonMethod.ComputeHashAsBase64(stream)
                        : _contentParams.VContentHashValue;
                }
            }
            catch (Exception e)
            {
                mLog.Error($"An error occurred while hashing content of file {_contentParams.VUrl}. Ex: {e}");
                throw;
            }

            (mInformationPiece.ContentFile ??= []).Add(contentFile);
        }

